#!/usr/bin/env python3
"""Build design/preview.html: the three mockup screens in ONE self-contained file.

Open preview.html with a double-click (no server, no build tools). The Lobby, Room and
How it works screens are switched with the page's own links (hash routes), so you can
click through them. Styles are inlined; only the Google Fonts stylesheet is loaded online
(without network the pages fall back to system fonts).

Run `python3 design/build-preview.py` after editing index.html, room.html, connect.html
or assets/at.css to regenerate it. Standard library only.
"""
import base64
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC_URL = "https://github.com/zakutana/agent-tournaments/blob/claude/upbeat-archimedes-d2yurc/SPEC.md"

PAGES = [  # route, source file, title
    ("lobby", "index.html", "Agent Tournaments · EventTrader"),
    ("room", "room.html", "Micro Weekly #14 · Agent Tournaments · EventTrader"),
    ("how", "connect.html", "How it works · Agent Tournaments · EventTrader"),
]
ROUTE_OF = {src: route for route, src, _ in PAGES}


def body_of(path: Path) -> str:
    html = path.read_text(encoding="utf-8")
    return re.search(r"<body>(.*)</body>", html, re.S).group(1)


def rewrite_links(fragment: str) -> str:
    def fix(m):
        href = m.group(1)
        if href == "../SPEC.md":
            return f'href="{SPEC_URL}" target="_blank" rel="noopener"'
        base, _, frag = href.partition("#")
        if base in ROUTE_OF:
            return f'href="#/{ROUTE_OF[base]}{":" + frag if frag else ""}"'
        return m.group(0)

    return re.sub(r'href="([^"]*)"', fix, fragment)


css = (HERE / "assets" / "at.css").read_text(encoding="utf-8")
icon = base64.b64encode((HERE / "assets" / "icon.svg").read_bytes()).decode()

templates = []
for route, src, _title in PAGES:
    frag = rewrite_links(body_of(HERE / src))
    templates.append(f'<template id="tpl-{route}">{frag}</template>')

titles = {route: title for route, _src, title in PAGES}

out = f"""<!DOCTYPE html>
<html lang="en" data-theme="dark">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Agent Tournaments · EventTrader</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo+Black&family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600;700&display=swap">
<link rel="icon" type="image/svg+xml" href="data:image/svg+xml;base64,{icon}">
<style>
{css}
/* preview only: anchors clear the sticky header */
main [id]{{scroll-margin-top:250px}}
html{{scroll-behavior:auto}}
</style>
</head>
<body>
<!-- PREVIEW BUILD: design only, no functionality. Generated by design/build-preview.py -->
<div id="app"></div>
{chr(10).join(templates)}
<script>
(function () {{
  var TITLES = {titles!r};
  var app = document.getElementById('app');

  function show() {{
    var parts = location.hash.replace(/^#\\/?/, '').split(':');
    var route = TITLES[parts[0]] ? parts[0] : 'lobby';
    var tpl = document.getElementById('tpl-' + route);
    app.replaceChildren(tpl.content.cloneNode(true));
    document.title = TITLES[route];
    var target = parts[1] && document.getElementById(parts[1]);
    if (target) target.scrollIntoView(); else window.scrollTo(0, 0);
  }}

  window.addEventListener('hashchange', show);
  show();

  document.addEventListener('click', function (e) {{
    var a = e.target.closest('a[href]');
    if (a) {{
      var href = a.getAttribute('href');
      if (href.charAt(0) === '#' && href.indexOf('#/') !== 0) {{   /* in-page anchor */
        e.preventDefault();
        var t = document.getElementById(href.slice(1));
        if (t) t.scrollIntoView({{ behavior: 'smooth' }});
      }}
      return;
    }}
    var b = e.target.closest('.switch button');                     /* visual only: toggle the active segment */
    if (b) {{
      b.parentNode.querySelectorAll('button').forEach(function (x) {{ x.classList.toggle('active', x === b); }});
      return;
    }}
    var c = e.target.closest('button.copybtn');                     /* visual only: no clipboard */
    if (c && !c.dataset.busy) {{
      var html = c.innerHTML;
      c.dataset.busy = '1';
      c.lastChild.textContent = 'Copied \\u2713';
      setTimeout(function () {{ c.innerHTML = html; delete c.dataset.busy; }}, 1400);
    }}
  }});
}})();
</script>
</body>
</html>
"""

target = HERE / "preview.html"
target.write_text(out, encoding="utf-8")
print(f"wrote {target} ({len(out) / 1024:.0f} KB)")
